package ru.alarmtrade.specmp.desktopApp

import androidx.compose.ui.res.painterResource
import androidx.compose.ui.unit.dp
import androidx.compose.ui.window.Window
import androidx.compose.ui.window.application
import androidx.compose.ui.window.rememberWindowState
import ru.alarmtrade.specmp.App

fun main() = application {
    val (versionName, versionCode) = loadDesktopAppVersion()

    Window(
        onCloseRequest = ::exitApplication,
        state = rememberWindowState(
            width = 1200.dp,
            height = 800.dp,
        ),
        title = "Pandora Spec",
        icon = painterResource("icon.png"),
    ) {
        App(appVersionName = versionName, appVersionCode = versionCode)
    }
}

private fun loadDesktopAppVersion(): Pair<String, Int> {
    val properties = java.util.Properties()
    val stream = requireNotNull(Thread.currentThread().contextClassLoader?.getResourceAsStream("version.properties")) {
        "version.properties is missing — it is generated by the desktopApp build"
    }
    stream.use(properties::load)
    return properties.getProperty("versionName") to properties.getProperty("versionCode").toInt()
}
