#!/bin/bash

# Generate multi-agent config files from .ai/*.md
# Usage: .ai/generate.sh [--check]
#   --check — для pre-commit: упасть, если сгенерированные файлы не добавлены в git

set -e

GREEN='\033[0;32m'
BLUE='\033[0;34m'
RED='\033[0;31m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
AI_DIR="$PROJECT_DIR/.ai"

if [ ! -d "$AI_DIR" ]; then
    echo -e "${RED}!${NC} .ai/ directory not found"
    exit 1
fi

concat_files() {
    local dir="$1"
    shift
    local files=("$@")
    local result=""

    for file in "${files[@]}"; do
        local filepath="$dir/$file"
        if [ -f "$filepath" ]; then
            if [ -n "$result" ]; then
                result="$result"$'\n\n---\n\n'
            fi
            result="$result$(cat "$filepath")"
        fi
    done
    echo "$result"
}

sync_local_files() {
    local source_dir="$1"

    [ -d "$source_dir" ] || return 0

    while IFS= read -r -d '' source; do
        local rel_path="${source#$source_dir/}"
        local target="$PROJECT_DIR/$rel_path"

        mkdir -p "$(dirname "$target")"

        case "$source" in
            *.md)
                cat > "$target" <<EOF
<!-- AUTO-GENERATED by .ai/generate.sh - DO NOT EDIT DIRECTLY -->
<!-- Source: .ai/agents/$rel_path -->

$(cat "$source")
EOF
                ;;
            *)
                cp "$source" "$target"
                ;;
        esac

        echo -e "${GREEN}+${NC} $rel_path"
    done < <(find "$source_dir" -type f -print0 | sort -z)
}

project_files=()
for f in "$AI_DIR"/*.md; do
    [ -f "$f" ] || continue
    basename=$(basename "$f")
    [ "$basename" = "README.md" ] && continue
    project_files+=("$basename")
done

if [ ${#project_files[@]} -eq 0 ]; then
    echo -e "${RED}!${NC} No .md files found in .ai/"
    exit 1
fi

shared_content=$(concat_files "$AI_DIR" "${project_files[@]}")

gen_header="<!-- AUTO-GENERATED by .ai/generate.sh - DO NOT EDIT DIRECTLY -->
<!-- Source: .ai/ - Edit files there and run: .ai/generate.sh -->"

has_claude_additions=false
[ -f "$AI_DIR/claude-additions.md" ] && has_claude_additions=true

filtered_files=()
for f in "${project_files[@]}"; do
    [ "$f" = "claude-additions.md" ] && continue
    filtered_files+=("$f")
done

if $has_claude_additions; then
    base_content=$(concat_files "$AI_DIR" "${filtered_files[@]}")
else
    base_content="$shared_content"
fi

claude_content="$base_content"
if $has_claude_additions; then
    claude_content="$claude_content"$'\n\n---\n\n'"$(cat "$AI_DIR/claude-additions.md")"
fi
echo "$gen_header

$claude_content" > "$PROJECT_DIR/CLAUDE.md"
echo -e "${GREEN}+${NC} CLAUDE.md"

echo "$gen_header

$base_content" > "$PROJECT_DIR/AGENTS.md"
echo -e "${GREEN}+${NC} AGENTS.md"

gemini_content="$gen_header
"
for f in "${filtered_files[@]}"; do
    gemini_content="$gemini_content
@.ai/$f"
done
echo "$gemini_content" > "$PROJECT_DIR/GEMINI.md"
echo -e "${GREEN}+${NC} GEMINI.md"

sync_local_files "$AI_DIR/agents"

# --- Скиллы и субагенты: .ai/skills/<skill>/ → Claude Code, Codex, Kimi Code, Gemini CLI ---
# Grok Build отдельно не генерируется: он сам читает CLAUDE.md, AGENTS.md, .claude/skills и .claude/agents.
#
# .ai/skills/<skill>/SKILL.md          → .agents/skills/<skill>/ (полная копия; Codex, Kimi, Gemini)
#                                      → .claude/skills/<skill>/SKILL.md
# .ai/skills/<skill>/roles/<role>.md   → .claude/agents/<name>.md, .codex/agents/<name>.toml,
#                                        .agents/agents/<name>.md (Kimi), .gemini/agents/<name>.md
# Frontmatter роли: name, description, claude_model, claude_tools, codex_effort,
# gemini_max_turns, gemini_timeout_mins.

skill_header() {
    echo "<!-- AUTO-GENERATED by .ai/generate.sh - DO NOT EDIT DIRECTLY -->"
    echo "<!-- Source: .ai/skills/$1 -->"
}

# Значение ключа из frontmatter.
fm_get() {
    awk -v key="$2" '
        NR == 1 && $0 == "---" { inside = 1; next }
        inside && $0 == "---" { exit }
        inside && index($0, key ":") == 1 { sub(key ":[ ]*", ""); print; exit }
    ' "$1"
}

# Frontmatter без обрамляющих ---.
fm_block() { awk 'NR == 1 && $0 == "---" { inside = 1; next } inside && $0 == "---" { exit } inside' "$1"; }

# Тело после frontmatter.
fm_body() { awk 'seen >= 2 { print; next } $0 == "---" { seen++ }' "$1"; }

toml_escape() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' <<<"$1"; }

# В кавычках: описание с «: » или «#» сломало бы YAML-frontmatter.
yaml_quote() { echo "\"$(toml_escape "$1")\""; }

gen_role() {
    local skill="$1" src="$2"
    local name description body header
    name="$(fm_get "$src" name)"
    [ -n "$name" ] || name="$(basename "$src" .md)"
    description="$(fm_get "$src" description)"
    body="$(fm_body "$src")"
    header="$(skill_header "$skill/roles/$(basename "$src")")"

    mkdir -p "$PROJECT_DIR/.claude/agents" "$PROJECT_DIR/.codex/agents" \
        "$PROJECT_DIR/.agents/agents" "$PROJECT_DIR/.gemini/agents"

    {
        echo "---"
        echo "name: $name"
        echo "description: $(yaml_quote "$description")"
        [ -n "$(fm_get "$src" claude_tools)" ] && echo "tools: $(fm_get "$src" claude_tools)"
        [ -n "$(fm_get "$src" claude_model)" ] && echo "model: $(fm_get "$src" claude_model)"
        echo "---"
        echo "$header"
        echo "$body"
    } > "$PROJECT_DIR/.claude/agents/$name.md"

    {
        echo "# AUTO-GENERATED by .ai/generate.sh - DO NOT EDIT DIRECTLY"
        echo "# Source: .ai/skills/$skill/roles/$(basename "$src")"
        echo "name = \"$name\""
        echo "description = \"$(toml_escape "$description")\""
        [ -n "$(fm_get "$src" codex_effort)" ] && echo "model_reasoning_effort = \"$(fm_get "$src" codex_effort)\""
        echo "developer_instructions = '''"
        echo "$body"
        echo "'''"
    } > "$PROJECT_DIR/.codex/agents/$name.toml"

    {
        echo "---"
        echo "name: $name"
        echo "description: $(yaml_quote "$description")"
        echo "---"
        echo "$header"
        echo "$body"
    } > "$PROJECT_DIR/.agents/agents/$name.md"

    {
        echo "---"
        echo "name: $name"
        echo "description: $(yaml_quote "$description")"
        [ -n "$(fm_get "$src" gemini_max_turns)" ] && echo "max_turns: $(fm_get "$src" gemini_max_turns)"
        [ -n "$(fm_get "$src" gemini_timeout_mins)" ] && echo "timeout_mins: $(fm_get "$src" gemini_timeout_mins)"
        echo "---"
        echo "$header"
        echo "$body"
    } > "$PROJECT_DIR/.gemini/agents/$name.md"

    echo -e "${GREEN}+${NC} agent $name (claude, codex, kimi, gemini)"
}

gen_skill() {
    local src_dir="$1" skill dst
    skill="$(basename "$src_dir")"
    dst="$PROJECT_DIR/.agents/skills/$skill"

    # Полная копия; локальные *.properties (креды) не трогаем.
    mkdir -p "$dst"
    find "$dst" -type f ! -name '*.properties' -delete
    find "$dst" -mindepth 1 -type d -empty -delete
    cp -R "$src_dir/." "$dst/"
    find "$dst" -name '.DS_Store' -delete

    local skill_md
    skill_md="$(echo "---"; fm_block "$src_dir/SKILL.md"; echo "---"; skill_header "$skill/SKILL.md"; fm_body "$src_dir/SKILL.md")"
    echo "$skill_md" > "$dst/SKILL.md"
    mkdir -p "$PROJECT_DIR/.claude/skills/$skill"
    echo "$skill_md" > "$PROJECT_DIR/.claude/skills/$skill/SKILL.md"
    echo -e "${GREEN}+${NC} skill $skill (.agents/skills, .claude/skills)"

    local role
    for role in "$src_dir"/roles/*.md; do
        if [ -f "$role" ]; then gen_role "$skill" "$role"; fi
    done
}

# Целевые папки принадлежат генератору: всё, чего нет в .ai/skills, удаляется. Локальные *.properties (креды) остаются.
GENERATED_DIRS=(.claude/skills .claude/agents .agents/skills .agents/agents .codex/agents .gemini/agents)

list_generated() {
    local d
    for d in "${GENERATED_DIRS[@]}"; do
        if [ -d "$PROJECT_DIR/$d" ]; then
            (cd "$PROJECT_DIR" && find "$d" -type f ! -name '*.properties' ! -name '.DS_Store')
        fi
    done | sort
}

before_files="$(list_generated)"
for d in "${GENERATED_DIRS[@]}"; do
    if [ -d "$PROJECT_DIR/$d" ]; then
        find "$PROJECT_DIR/$d" -type f ! -name '*.properties' -delete
        find "$PROJECT_DIR/$d" -mindepth 1 -type d -empty -delete
    fi
done

for skill_dir in "$AI_DIR"/skills/*/; do
    if [ -f "$skill_dir/SKILL.md" ]; then gen_skill "${skill_dir%/}"; fi
done

while IFS= read -r f; do
    [ -n "$f" ] && echo -e "${RED}-${NC} removed $f (нет в .ai/skills)"
done < <(comm -23 <(echo "$before_files") <(list_generated))

for d in .grok/skills .grok/agents; do
    if [ -d "$PROJECT_DIR/$d" ] && [ -n "$(ls -A "$PROJECT_DIR/$d")" ]; then
        echo -e "${RED}!${NC} $d не пуст: скилы и субагенты пишутся только в .ai/skills (Grok читает .claude/)"
    fi
done

# --- Хуки агентов: .ai/hooks/* → .claude/settings.json, .gemini/settings.json, .codex/hooks.json ---
# Merge: остальные ключи сохраняются; запись хука с той же command (или тем же скриптом *.sh/*.py,
# например после переезда) заменяется, а не дублируется.

merge_hooks() {
    local src="$AI_DIR/hooks/$1" target_dir="$PROJECT_DIR/$2" dst="$PROJECT_DIR/$2/$3"

    [ -f "$src" ] || return 0
    if ! command -v python3 >/dev/null 2>&1; then
        echo -e "${RED}!${NC} python3 not found: $2/$3 not updated"
        return 0
    fi
    if [ -e "$target_dir" ] && [ ! -d "$target_dir" ]; then
        echo -e "${RED}!${NC} $2 is a file, not a directory: $2/$3 not updated"
        return 0
    fi
    mkdir -p "$target_dir"
    python3 -I - "$src" "$dst" <<'PY'
import json, re, sys
from pathlib import Path

src, dst = Path(sys.argv[1]), Path(sys.argv[2])

def key(command):
    m = re.search(r"[\w.-]+\.(?:sh|py)\b", command or "")
    return m.group(0) if m else command

def keys(item):
    return {key(h.get("command")) for h in item.get("hooks", [])} if isinstance(item, dict) else set()

def merge(base, add):
    if isinstance(base, dict) and isinstance(add, dict):
        return {**base, **{k: merge(base[k], v) if k in base else v for k, v in add.items()}}
    if isinstance(base, list) and isinstance(add, list):
        added = set().union(*map(keys, add))
        return [b for b in base if b not in add and not keys(b) & added] + add
    return add

current = json.loads(dst.read_text(encoding="utf-8")) if dst.exists() else {}
merged = merge(current, json.loads(src.read_text(encoding="utf-8")))
dst.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
PY
    echo -e "${GREEN}+${NC} $2/$3"
}

HOOK_TARGETS=(.claude/settings.json .gemini/settings.json .codex/hooks.json)
merge_hooks claude-settings.json .claude settings.json
merge_hooks gemini-settings.json .gemini settings.json
merge_hooks codex-hooks.json .codex hooks.json

# pre-commit видит только изменения отслеживаемых файлов: новые сгенерированные (новый скил) ловим сами.
if [ "${1:-}" = "--check" ]; then
    untracked="$(cd "$PROJECT_DIR" && git status --porcelain --untracked-files=all -- \
        CLAUDE.md AGENTS.md GEMINI.md "${GENERATED_DIRS[@]}" "${HOOK_TARGETS[@]}" | sed -n 's/^?? //p')"
    if [ -n "$untracked" ]; then
        echo -e "${RED}!${NC} сгенерированные файлы не добавлены в git — git add и повтори коммит:"
        echo "$untracked"
        exit 1
    fi
fi

echo ""
echo -e "${BLUE}Done!${NC}"
