package ru.alarmtrade.specmp.feature.device.interaction.domain.model

/** Что переводим в загрузчик: основную программу блока или Bluetooth-модуль (только BLE). */
enum class BootModeTarget { MainProgram, BluetoothModule }

/**
 * Исход команды «перейти в загрузчик». Неверный PIN — не ошибка операции, а исход, который экран обрабатывает
 * диалогом ввода PIN; прочие сбои приходят как `Response.Error`.
 */
enum class BootModeResult {
    /** Блок принял команду (или уже в загрузчике): дальше он перезагрузится. */
    Entered,

    /** BLE: блок не принял PIN программирования (сохранённый или по умолчанию). */
    WrongPin
}

/**
 * Перезагрузка блока, которую приложение само вызвало и ждёт: связь при ней обрывается намеренно,
 * и экраны не должны показывать это как потерю связи.
 */
enum class DeviceReboot {
    /** Блок уходит в загрузчик (перед обновлением прошивки). */
    ToBoot,

    /** Блок выходит из загрузчика в рабочий режим (после обновления прошивки). */
    ToMain
}
