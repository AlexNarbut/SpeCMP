package ru.alarmtrade.specmp.feature.supportchat.presentation.platform

/**
 * Платформенный порт жизненного цикла локальных копий вложений.
 *
 * Пикер (`SupportChatFilePicker`) копирует выбранный файл в собственный каталог
 * приложения; копия нужна, пока сообщение не подтверждено сервером (в т.ч. для
 * outbox после рестарта). ViewModel сообщает, когда копия больше не нужна: эхо
 * сервера заменило сообщение, пользователь удалил чип или неотправленное сообщение.
 *
 * Реализация удаляет только файлы из своего каталога — пути вне его (Desktop
 * отправляет оригинал пользователя) игнорируются.
 */
interface SupportChatAttachmentFiles {
    fun discard(path: String)
}
