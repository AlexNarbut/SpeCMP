package ru.alarmtrade.specmp.core.common

/**
 * Контракт компонентов, обязанных очистить своё состояние при смене аккаунта.
 *
 * App-scoped синглтоны (репозитории, холдеры сессий) переживают логаут, поэтому
 * их состояние (открытые соединения, кэши identity, незакрытые сессии) должно
 * сбрасываться явно. Точкой очистки владеет `LogoutUseCase`: он выполняет logout
 * и проходит по всем зарегистрированным в DI `AuthCloseable`, вызывая [release].
 *
 * Реализация не должна бросать исключения: ошибки очистки логируются
 * реализацией и не отменяют logout.
 */
interface AuthCloseable {

    /**
     * Очищает состояние, привязанное к текущему аккаунту.
     * Вызывается только после успешного logout.
     */
    suspend fun release()
}
